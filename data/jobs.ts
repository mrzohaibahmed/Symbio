export function getJobBySlug(slug: string): Job | undefined {
  return jobs.find((job) => job.slug === slug && job.isOpen);
}

export function getRelatedJobs(job: Job, limit = 3): Job[] {
  return job.relatedJobIds
    .map((id) => jobs.find((item) => item.id === id && item.isOpen))
    .filter((item): item is Job => Boolean(item))
    .slice(0, limit);
}

export function getOpenJobs(): Job[] {
  return jobs.filter((job) => job.isOpen);
}
